            	    <p></p><h1><b></b>OUR
RECTOR MAJOR<b></b></h1>

<h2>FR.FERNANDEZ
ARTIME ANGEL SDB</h2>

<p><strong></strong>Rev. Fr. Ángel Fernández Artime
was born on 21 August 1960 in Luanco-Gozon, Asturias, Spain; he became a member
of the Salesians of Don Bosco on 3 September 1978, and was ordained a priest on
4 July 1987 in León. He earned a degree in Pastoral <b></b>Theology and a Licentiate
in Philosophy and Pedagogy. He was the Provincial Superior of León from 2000 to
2006. After being part of the Preparatory Committee which prepared the 26th
General Chapter of the Salesian Society in 2009, he was appointed the Provincial
Superior of South Argentina, based in Buenos Aires. In this capacity he also
got to know and work personally with the then Archbishop of Buenos Aires,
Cardinal Jorge Mario Bergoglio, today Pope Francis. On 23 December 2013, he was
appointed Superior of the new Province of Mediterranean Spain. But before he
could take on that new role, on 25 March 2014 he was elected by the General
Chapter 27 as the Rector Major of the Salesian Society and the 10th Successor
of Don Bosco.</p>

<p>The 28th General Chapter of the
Salesian Congregation renewed the mandate of the Rector Major of the Salesians
of Don Bosco and Father of the Salesian Family of Fr. Ángel Fernández Artime
for the six-year term 2020-2026.</p>

<p>Fr. Ángel Fernández Artime is the
10th Successor of Don Bosco. He is ‘Don Bosco alive’ today. He animates and
promotes, in continuity with its predecessors, the sense of unity of the
different groups of the Family, to develop that Great spiritual and pedagogical
Movement dreamed of by Don Bosco. Attentive and open to the news and calls of
the Hol<strong></strong>y Spirit in the Church, he makes himself close to the young, available
to the poorest and those who do not know the love of God and the joy of the
Gospel.<strong></strong></p>

<p><strong><a target="_blank" rel="nofollow" href="https://www.facebook.com/agenziaans/videos/2798807056907686/">Video-Message of the Rector Major</a>: </strong><em>“Young people need us, our presence, those who know how to
communicate the love of God. Here is the commitment for this new six year term:
To bring God to young people and especially to the poorest ones. We were born
for them.”</em></p>

<p>Nepal Don Bosco School/College<strong>,</strong>&nbsp;with joy and great esteem,
welcomes Fr. Ángel Fernández Artime, as Don Bosco would have done and, while
entrusting him to God, assures him of the affection and the sincerest
collaboration in the Educommunication and service to young people, especially
the poorest.</p>

<p><strong>Best wishes Fr. Ángel from
all the NDBS Family educating communities in the world!</strong></p>

