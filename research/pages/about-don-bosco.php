            	    <p><b></b></p><h2><b>DON
BOSCO</b></h2><b>

<p></p></b><p>Saint
John Bosco , popularly known as Don Bosco (Italian for Father Bosco) was born
at Becchi, in Piedmont, Italy on August 16, 1815. From a very young age, he had
decided that he had been called to work for the poor boys of that era when
Europe was under the grip of the Industrial Revolution, and many young people
who came to the cities to study or in search of work fell an easy prey to the
many social evils of the time.</p><b><p></p>

<p></p></b><p>After
being ordained a priest of the Catholic Church in 1841, Don Bosco came to the
rescue of these poor boys with his novel method of educating youth through
total dedication and personal involvement in their lives and problems.</p>

<p>Don
Bosco was attuned to the needs of his society. He did not visualize education
in isolation from the community within whose parameters it functioned.
Vocational guidance, vocational training, job placement and follow-up were as
integral to Don Bosco's scheme of things as they are in modern education.</p>

<p>To
ensure that his total dedication to their cause shone through his actions, he
based his education on the three great principles of Reason, Religion and
Loving-Kindness, loving those to whom he dedicated his life as a caring father,
and doing everything possible for their welfare. </p>

<p>Don
Bosco’s paradigm of education, globally recognized as ‘Preventive System’, is
embedded on three Rs: REASON (Intellectual Growth– IQ), RELATIONSHIP (Emotional
Growth – EQ) and RELIGION (Spiritual Growth – SQ).</p>

<p>Don
Bosco was attuned to the needs of his society. He did not visualize education
in isolation from the community within whose parameters it functioned.
Vocational guidance, vocational training, job placement and follow-up were as
integral to Don Bosco's scheme of things as they are in modern education.</p>

<p>The
system of education that emerged from these principles of Don Bosco is
popularly known as the Preventive System and is the system that is followed in Nepal
Don Bosco School/College. The system aims at creating a generation of young men
and women steeped not only in sound knowledge-based education but also in a
strong value-based education for life.</p>

<p>Currently
serving in 134 countries across the globe, Don Bosco Fathers and Brothers are
at the service of young people, shaping their career and accompanying them as a
friend for a meaningful and fulfilling life.</p>

<p>The
Unique Selling Proposition (USP) of Don Bosco institutions is the family
ambience, a home-away-from-home setting. Don Bosco used to say, “It is not
enough to love the young. They must know that they are loved.”</p>

<p>Nepal
Don Bosco School/College is a branch of Don Bosco International Educational
Services, a global brand for quality.</p>







<h1>SALESIANS IN THE WORLD</h1><div>We are part of a world-wide family. Check it out on <a target="_blank" rel="nofollow" href="http://www.sdb.org/">www.sdb.org</a></div>

<br><p></p><p><b>John Bosco (1815-1888) Beatified 2-5-1929 Canonized 1-4-1934</b>&nbsp;was born in the evening of 16 August 1815 in the hillside hamlet of Becchi, Italy. He was the youngest son of Francesco Bosco (1784–1817) and Margherita Occhiena. He had two older brothers, Antonio and Giuseppe (1813–1862). The Boscos of Becchi were farmhands of the Moglian Family. John Bosco was born into a time of great shortage and famine in the Piedmonteses countryside, following the devastation wrought by the Napoleonic wars and a drought in 1817.<br></p><p>When he was little more than two years old, his father Francesco died, leaving the support of three boys to his mother, Margherita. She played a strong role in Bosco's formation and personality and was an early supporter of her son's ideals.<br>Poverty prevented any serious attempt at schooling. John's early years were spent as a shepherd, and he received his first instruction from a parish priest. His childhood experiences are thought to have inspired him to become a priest. At the time, being a priest was generally seen as a profession for the privileged classes, rather than farmers, although it was not unknown. Some biographers portray his older brother Antonio as the main obstacle for Bosco's ambition to study, as the brother protested that John was just "a farmer like us!"<br>On a cold morning of February 1827, John left his home and went to look for work as a farm-servant. At 12, he found life at home unbearable because of the continuous quarrels with Antonio. Having to face life by himself at such a young age may have developed his later sympathies to help abandoned boys. After begging unsuccessfully for work, Bosco ended up at the wine farm of Louis Moglia.Although Bosco could pursue some studies by himself, he was not able to attend school for two more years. In 1830 he met Joseph Cafasso, a young priest who identified some natural talent in him and supported his first schooling. In 1835 Bosco entered the seminary at Chieri, next to the Church of the Immacolata Concezione. In 1841, after six years of study, he was ordained priest on the eve of Trinity Sunday by Archbishop Franzoni of Turin.

<br></p><p><br></p><h4><b>Life&nbsp;of&nbsp;Don&nbsp;Bosco&nbsp;in&nbsp;Detail</b></h4><p><b></b>

</p><p><img width="1024" alt="donbosco-1024x963" src="https://donbosco208409380.wpcomstaging.com/wp-content/uploads/2018/05/donbosco-1024x963.jpg" height="963"></p>
<p>John Bosco, the father and friend of youth was born on August 16, 1815, in a peasant family in the little hamlet of Becchi, some 20 kilometers from Turin, Italy. When John was only 2 years old, his Father Francis Bosco passed away. His grief stricken mother, Margaret Occiena Bosco, had a harrowing time to bring him up.</p>
<p>At the age of nine, John had a mysterious dream which led him to his future mission. He decided to become a priest and commit his life to the welfare of young people.</p>
<p>To complete his education John had to do his share of work on the family farm and study during his spare time. Working as a servant, teaching, assisting a tailor, doing chores for a blacksmith and keeping score at a billiard table were some of the things he did in order to pay for his food, lodging and tuition while at school. In due course, John entered the seminary and was ordained a priest on June 5, 1841. From then on he was known as Don Bosco (Father Bosco).</p>
<p>Very soon Don Bosco became a frequent visitor to the poorer quarters of the city. This young priest was distressed by the swarms of neglected children whom he encountered. In the miserable garrets and cellars which he visited, he found exemplified all the evils of overcrowding, all the terrible effects of herding the young and innocent with those already corrupt. In the prisons he met youth serving terms for every type of crime, while during his evening walks he constantly met bands of young people fighting, making themselves a danger to the society. He decided that the work of his life would be to redeem these miserable youths.</p>
<p>Don Bosco’s work for boys started with one boy, a mason’s apprentice. Soon this boy brought others and the number of “Don Bosco’s friends” multiplied. He gave them facilities for games and taught them their religion.</p>
<p>In 1853, two small workshops had been opened, one a shoemakers’, the other a tailor’s for teaching the unemployed youngsters a trade in order to provide them with the means of earning an honest livelihood. A workshop for teaching carpentry was soon followed by others for book-binding and cabinet making.</p>
<p>All this while from his ‘old boys’, Don Bosco had been building up a ‘society of men’ who would help him to develop his work and would carry it on when he died. In December 1859 these young were formed into a simple society for this purpose. In May 1862 they took the vows of poverty, chastity and obedience – thus forming a true religious congregation. In 1869 this community of men was officially recognized by the Catholic Church and took the name “Salesians” after St. Francis de Sales.</p>
<p>Don Bosco called his methods of education the ‘Preventive System’ based on REASON, RELIGION and KINDNESS. He told his disciples that education was to be based on love, on selfless service for the mental, emotional, moral and spiritual growth of the pupils.</p>
<p>Don Bosco also founded a congregation of religious nuns known as the “Daughters of Mary Help of Christians” to educate girls with the same method as the Salesian used to educate the boys.</p>
<p>Today, a hundred and twenty years after Don Bosco’s death, 36000 Priests, Brothers and Sisters carry out his work in 134 countries around the world. They are engaged in a wide variety of developmental works directed to the welfare of the young academic, agricultural and technical school, youth centers, hostels and parishes, catechetics, mass media and social communications, youth counseling and rehabilitation centers and a host of special services for the delinquents and the marginalised youth.</p>
<p>Don Bosco died on January 31, 1888 at the age of seventy three. He was declared a saint on April 1, 1934. His feast day is celebrated on January 31 every year.</p>
