</p><p><b>AIM
OF THE INSTITUTION</b></p>



<p>Through our Don Bosco system of
education, we aim to form in our boys and girls, the habits of piety, virtue,
discipline and self-reliance. The school aims to foster in the students the
sense of responsibility so that they become dutiful and useful citizen of their
motherland, Nepal.</p>



<p>Studies are designed to select and
prepare students for the S.E.E. and N.E.B. examinations of Nepal Board of
Education. Subjects taught include all branches of Nepali and English Language
and Literature, Mathematics, Science, Social Studies of Nepal, General
Knowledge, Moral Education, Arts and Crafts, Games and Sports and Other
Cultural &amp; Co-curricular Activities. Counselling Opportunities and Computer
Education for students are imparted as part of the curriculum. </p>



<p><b>SCHOOL TERMS</b></p>



The school year 2023 begins
from the month of April 19 2023 (Baisakh 6, 2080) and continues till March 2024 (Chaitra 2077). We will have Six-days of classes a week: Sunday to
Friday. <strong>Saturdays</strong> are holidays. Alternative <strong>Sundays </strong>will be
Holidays as mentioned in the Monthly Calendar. Class timing is from 8:30 AM to
3:00 PM. While school working hours are from 8:00 AM to 4:00 PM.



<br>Major holidays are given thrice a
year, Dashain – Tihar, winter and a Annual Holiday.
Parents should see to it that their child comes to school on time everyday and
on the specified day after the holidays. Those coming late without sufficient
cause and prior information may be fined or dropped from the school roll. At
the beginning of the scholastic year, children who do not present themselves
within the first three days without information will be ticked off from the
list. Please make sure that you have at home a school calendar that is prepared
for every month which has been incorporated in the school diary as well.



<br><strong></strong><br><p><b>PROMOTION</b><strong></strong>



<br>Promotion to the next class at the
end of the academic year will be based on the performance of the student in all
the term examinations conducted during the year; hence, it does not depend only
on the final term examinations. For those who fail, the school authority will
decide whether they should be given a chance to repeat in the same class or
leave the school.



</p><p><b>BOOK STORE</b></p>



<p>Text books are not provided from the
school. The text book lists are available at the school office at the time of
admission.</p>



<p><b>DISCIPLINARY
MATTERS</b></p>



<p>Students are not allowed to bring to
school any electronic gadgets or other expensive jewels/articles/gadgets. The
school authority will not be responsible for their loss, instead if found just
penal action will be taken. </p>



<p>Students must come to school neatly
dressed in school uniform. They must <strong>reach
the school at least 15 minutes</strong> before the school begins. When leaves
are taken, the reason must be entered in the school diary, and parent’s or
guardian’s signature is compulsory. For every term examination, 85% of
attendance is required to appear for examinations.</p>



<p><strong>LIBRARY &amp; LABORATORY</strong></p>



<p>We facilitate our students with a
well equipped library and laboratories in the school. A library and laboratory
fee is charged annually for upgrading laboratory with facilities and library
with books.</p>



<p><strong>TELEPHONE</strong></p>



<p>Telephone calls to the school for
information or to the principal should be made only between 9:30 am – 3:30 pm.
You should not make any phone call to the children, as they will not be called
to the telephone. Message may be left with the receptionist who will
communicate it to the ward at the earliest.</p>



<p><strong><em>No mobile/cell phones are allowed by
the students in the school.</em></strong></p>



<p><b>EMERGENCY
MEDICAL TREATMENT</b></p>



<p>In
case a student falls ill in the school or meet with accident, the school
authority will contact the parents/guardians at the earliest. In case of
emergency, the student may be taken to the nearest health care centre/hospital
for treatment. All medical expenses are to be met by the parents/guardians.</p>



<p><strong>EXTRA
CURRICULAR ACTIVITIES</strong></p>



<ul><li>Basketball</li><li>Football</li><li>Volleyball</li><li>Taekwondo</li><li>Cricket
</li><li>Arts
&amp; Crafts</li><li>Music
</li><li>Dance</li><li>Badminton
&amp; Table Tennis</li></ul>



<p>&nbsp; &nbsp; &nbsp; &nbsp;  *<strong><em>As per the requirements and suggestions other
activities can be conducted.</em></strong></p>



<p><strong>TRANSPORT SERVICE</strong></p>



<p><strong>Bus
Fees cover twelve months and are to be paid either monthly or two </strong><strong>months
at a time by 15th of the second month. No one way service/ payment:
For the cancellation of bus service, information should be given before 15th
of previous month.&nbsp;</strong></p>



